# -*- coding: utf-8 -*-
"""Derive a four-corner component Pose dataset without touching source labels.

The source may contain additional pin landmarks after the four semantic PCB
corners.  Runtime pin locations can then be projected from a component profile,
which is the same contract used by the photoresistor module.
"""
from __future__ import annotations

import argparse
from copy import deepcopy
import json
from pathlib import Path
import shutil
from typing import Any

from pose_labeling import PoseLabelDataset


MARKER_NAME = ".corner-pose-derived.json"


def _rewrite_label(source: Path, destination: Path, *, source_count: int) -> None:
    expected = 5 + source_count * 3
    keep = 5 + 4 * 3
    lines: list[str] = []
    raw = source.read_text(encoding="utf-8")
    for line_number, raw_line in enumerate(raw.splitlines(), start=1):
        fields = raw_line.split()
        if not fields:
            continue
        if len(fields) != expected:
            raise ValueError(
                f"{source}:{line_number}: expected {expected} values for "
                f"{source_count} keypoints, found {len(fields)}"
            )
        lines.append(" ".join(fields[:keep]))
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text("\n".join(lines) + ("\n" if lines else ""), encoding="utf-8")


def _prepare_destination(destination: Path, source_yaml: Path, *, overwrite: bool) -> None:
    if not destination.exists():
        return
    if not any(destination.iterdir()):
        return
    if not overwrite:
        raise SystemExit(
            f"destination is not empty: {destination}; rerun with --overwrite "
            "only for a dataset previously generated by this tool"
        )
    marker = destination / MARKER_NAME
    if not marker.is_file():
        raise SystemExit(
            f"refusing to replace unmarked directory: {destination}"
        )
    payload = json.loads(marker.read_text(encoding="utf-8"))
    if Path(payload.get("source_yaml", "")).resolve() != source_yaml.resolve():
        raise SystemExit(
            "refusing to replace a derived dataset created from another source"
        )
    shutil.rmtree(destination)


def derive(
    source_yaml: Path,
    destination: Path,
    *,
    overwrite: bool = False,
    positive_only: bool = False,
) -> dict[str, Any]:
    source_yaml = source_yaml.resolve()
    destination = destination.resolve()
    dataset = PoseLabelDataset(source_yaml)
    if dataset.keypoint_count <= 4:
        raise SystemExit(
            f"source already has {dataset.keypoint_count} keypoints; expected more than four"
        )
    if destination == dataset.dataset_root.resolve():
        raise SystemExit("destination must differ from the source dataset")
    _prepare_destination(destination, source_yaml, overwrite=overwrite)

    counts: dict[str, int] = {}
    skipped_empty: dict[str, int] = {}
    active_keys: set[str] = set()
    for split in ("train", "val", "test"):
        images = dataset.images(split)
        counts[split] = 0
        skipped_empty[split] = 0
        image_root = dataset.image_roots.get(split)
        if image_root is None:
            continue
        for image in images:
            source_label = dataset.label_path(image, split)
            if not source_label.is_file():
                raise FileNotFoundError(f"missing source label: {source_label}")
            if positive_only and not source_label.read_text(encoding="utf-8").strip():
                skipped_empty[split] += 1
                continue

            relative = image.relative_to(image_root)
            target_image = destination / "images" / split / relative
            target_image.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(image, target_image)

            target_label = (destination / "labels" / split / relative).with_suffix(".txt")
            _rewrite_label(
                source_label,
                target_label,
                source_count=dataset.keypoint_count,
            )
            active_keys.add(dataset.key(image, split))
            counts[split] += 1

    review_records: dict[str, dict[str, Any]] = {}
    for key in sorted(active_keys):
        record = dataset.review.records.get(key)
        if not isinstance(record, dict):
            continue
        derived_record = deepcopy(record)
        derived_record["keypoint_count"] = 4
        derived_record["derived_from_keypoint_count"] = dataset.keypoint_count
        review_records[key] = derived_record
    review_path = destination / ".pose-label-studio" / "review.json"
    review_path.parent.mkdir(parents=True, exist_ok=True)
    review_path.write_text(
        json.dumps(review_records, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )

    report: dict[str, Any] = {
        "source_yaml": str(source_yaml),
        "source_dataset": str(dataset.dataset_root.resolve()),
        "destination": str(destination),
        "source_keypoint_count": dataset.keypoint_count,
        "derived_keypoint_count": 4,
        "splits": counts,
        "positive_only": positive_only,
        "skipped_empty": skipped_empty,
        "review_records": len(review_records),
    }
    (destination / MARKER_NAME).write_text(
        json.dumps(report, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    return report


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-data", type=Path, required=True)
    parser.add_argument("--destination", type=Path, required=True)
    parser.add_argument("--overwrite", action="store_true")
    parser.add_argument(
        "--positive-only",
        action="store_true",
        help="exclude empty-label images instead of copying them as negatives",
    )
    args = parser.parse_args()
    report = derive(
        args.source_data,
        args.destination,
        overwrite=args.overwrite,
        positive_only=args.positive_only,
    )
    print(json.dumps(report, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
